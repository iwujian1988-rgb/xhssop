export const fullTitleFormulaCatalog = RAW_FORMULAS.split('\n').map(line => {
  const [id, formula] = line.split('|');
  const numericId = Number(id);
  return {
    id,
    formula,
    trigger_type: TRIGGERS.find(group => numericId <= group.max)?.type || '其他',
  };
});

const DENSE_DIRECTORY_FORMULA_IDS = new Set([
  '1', '7', '8', '11', '13', '14', '15', '17', '19', '20',
  '26', '27', '28', '29', '30', '31', '32', '52', '72', '75',
]);

export function getDenseDirectoryTitleFormulas(topic = '') {
  return fullTitleFormulaCatalog.filter(item => {
    if (!DENSE_DIRECTORY_FORMULA_IDS.has(item.id)) return false;
    if (item.id === '29' && !/词汇|单词|词语|表达替换/.test(topic)) return false;
    if (item.id === '72' && !/自测|测试|测一测|诊断/.test(topic)) return false;
    return true;
  });
}
