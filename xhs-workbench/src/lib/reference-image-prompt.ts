function pickOne(items: string[]) {
  return items[Math.floor(Math.random() * items.length)] || '';
}

// 内部目录 ID（CH-085 / AU-001 / JF-011 / GRAM-0001 等）绝不能进入文生图 prompt，
// 否则图像模型会一五一十地把它们画到封面上。item.note 经常带这种 ID，组装 prompt 前先剥。
function stripInternalIds(text: string): string {
  return text
    .replace(/[（(]\s*[A-Z]{2,4}-\d{2,4}\s*[）)]/g, '')
    .replace(/\b[A-Z]{2,4}-\d{2,4}\b/g, '')
    .replace(/[（(]\s*[）)]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

export function buildReferenceImagePrompt(card: CompetitorCreativeCard, cover: DenseDirectoryCoverPayload) {
  const core = TEMPLATE_CORE[card.renderer_id];
  if (!core) throw new Error(`模板 ${card.renderer_id} 尚未配置文生图提示词`);

  const variationPool = TEMPLATE_VARIATIONS[card.renderer_id] || [];
  const variation = variationPool.length ? pickOne(variationPool) : '';

  const content = cover.sections.map((section, index) => [
    `${index + 1}. ${section.heading}`,
    ...section.items.map(item => {
      const note = item.note ? stripInternalIds(item.note) : '';
      return `- ${item.primary}${item.secondary ? `｜${item.secondary}` : ''}${note ? `（${note}）` : ''}`;
    }),
  ].join('\n')).join('\n');

  return [
    '直接文生图，输出一张完整的3:4竖版小红书封面成品。不要上传参考图，不要图生图编辑。',
    '【模板骨架·必须保持一致】',
    core,
    variation ? `【本次允许变化的细节·只改这些】\n${variation}\n注意：主体风格、配色、标题字号层级和版式骨架不要变；只让人物姿势/图标/小点缀有新鲜感。` : '',
    '【本篇必须写入画面的文案——一字不改地画出来】',
    `主标题：${cover.title}`,
    `副标题：${cover.subtitle || '（无）'}`,
    `正文内容：\n${content}`,
    '【正文画法硬约束·防重复填充】',
    '正文必须严格按上面清单的顺序逐条画一次：每条法语搭配只出现一次、每条中文释义只出现一次。',
    '禁止为"填满画面"而重复、复制、粘贴同一条短语；禁止新增清单外的额外条目；禁止省略清单里的任何一条。',
    '若某列空间不足，宁可让该列末尾留白或略缩字号，也不要用重复内容填充空缺位置。',
    '【字体与排版·必须像真实印刷品】',
    '所有文字必须像真实排版字体，不要 AI 假字感。中文用思源黑体或苹方这类现代无衬线，法语用 Helvetica、SF Pro 或 Inter 这类无衬线。',
    '所有文字避免细长、窄高、发虚、笔画过细；标题和重点文字要厚实稳定，正文和小字也要清晰结实。',
    '字数较多时优先换行、略微缩小字号或增加行高，绝对不要通过压窄字形、拉高字形、拉细笔画来塞字。',
    '禁止文字重叠、串行、遮挡、越界；整体要像人工精修排版，不要像 AI 生成的伪排版。',
    '【硬性要求】',
    '画面必须填满整张图，禁止大片留白或下半截空白。',
    '中文和法语清楚可读、无乱码、无断词、无重叠；标题在手机缩略图仍能看清。',
    '只使用上面的本篇文案，不要编造品牌、出版社、作者、账号、二维码、咨询入口。',
    card.renderer_id === 'course_roadmap'
      ? '底部承接只写资料包/练习路径，禁止一对一、直播课、老师批改、无限答疑等服务承诺。'
      : '',
  ].filter(Boolean).join('\n\n');
}

