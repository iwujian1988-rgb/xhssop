    '所有文字避免细长、窄高、发虚、笔画过细；标题和重点文字要厚实稳定，正文和小字也要清晰结实。',
    '字数较多时优先换行、略微缩小字号或增加行高，绝对不要通过压窄字形、拉高字形、拉细笔画来塞字。',
